"""Block G: regenerate results/hardening/BLOCK_G_TABLES.md from the sweep CSVs (read-only analysis, no simulation).

    python -X utf8 results/hardening/analysis/blockg_tables.py      (run from the project root)

Every cell: mean ± 95% CI half-width over independent runs (metrics.summarize: Student t, df = n - 1), with n.
Block F reference values come from results/adversarial (never modified)."""
import csv
import glob
import json
import os
import sys

sys.path.insert(0, os.getcwd())
import adversarial
from metrics import summarize

H, F = os.path.join("results", "hardening"), os.path.join("results", "adversarial")
D = ("100", "200", "300")
out = []


def load(path):
    rows = list(csv.DictReader(open(path, encoding="utf-8"))) if os.path.exists(path) else []
    for r in rows:
        for k, v in r.items():
            try:
                r[k] = float(v)
            except ValueError:
                pass
    return rows


def cell(vals, pct=True, dec=1):
    m, _, ci, n = summarize([v for v in vals if v is not None and v == v])
    if n == 0:
        return "–"
    s = 100 if pct else 1
    return f"{m * s:.{dec}f} ± {ci * s:.{dec}f} (n={n})" if ci == ci else f"{m * s:.{dec}f} (n={n})"


def attacker(r):
    if r["ONOFF_PERIOD_S"] > 0:
        return f"phased {r['ONOFF_DUTY']:g}/{r['ONOFF_PERIOD_S']:g} s"
    return f"per-second {r['MALICIOUS_COOPERATION']:g}"


def pivot(title, rows, keyf, header, value, pct=True, where=lambda r: True, dec=1):
    rows = [r for r in rows if where(r)]
    out.append(f"\n**{title}**\n")
    out.append("| " + " | ".join(header) + " | " + " | ".join(f"{d} vehicles" for d in D) + " |")
    out.append("|" + "---|" * (len(header) + len(D)))
    for k in sorted({keyf(r) for r in rows}, key=str):
        sel = [r for r in rows if keyf(r) == k]
        out.append("| " + " | ".join(str(x) for x in k) + " | " + " | ".join(
            cell([value(r) for r in sel if r["density"] == float(d)], pct, dec) for d in D) + " |")


def completion(sweep, settings, first):
    done = raws = 0
    for s in settings:
        f = os.path.join(H, sweep, adversarial.name(s))
        if os.path.exists(os.path.join(f, "summaries", "experiment_config.json")):
            done += 1
            raws += len([p for p in glob.glob(os.path.join(f, "raw", "d*_r*.json.gz")) if "__" not in p])
    out.append(f"| {sweep} | {len(settings)} | {done} | {raws} | runs {first}-{first + 29} |")


choice = lambda f: json.load(open(os.path.join(H, f), encoding="utf-8")) if os.path.exists(os.path.join(H, f)) else None
k_choice, c_choice = choice("G3a_calibration_choice.json"), choice("G2_selection.json")   # historical record
c_fixed = choice("G2_selection_corrected.json")                                           # G4.1 corrected selection
k = k_choice["chosen_k"] if k_choice else None
committee = tuple(c_fixed["chosen"]) if c_fixed and c_fixed["chosen"] else None
out.append("# Block G: hardening sweep tables\n")
out.append("Generated by `results/hardening/analysis/blockg_tables.py` from `results/hardening/*_runs.csv` (Block F "
           "references from `results/adversarial/`). Cell = mean ± 95% CI half-width over independent runs "
           "(Student t), n = runs. Seeds: runs 0-29 (G3a: held-out runs 30-59); seed = 10000 + 100·density + run. "
           "Gate 0.70 throughout. The VeReMi ML model is not used. Pre-registered rules: "
           "`results/hardening/PREREGISTERED_RULES.json`.\n")
out.append("## Sweep completion\n\n| sweep | settings | completed | raw records | seeds |\n|---|---|---|---|---|")
for sweep, (first, settings) in adversarial.g_sweeps(k, committee).items():
    if os.path.isdir(os.path.join(H, sweep)):                # only sweeps that were run
        completion(sweep, settings, first)

# ---------------------------------------------------------------- G1
g1t, g1f = load(os.path.join(H, "G1_trust_runs.csv")), load(os.path.join(H, "G1_forgery_runs.csv"))
if g1t:
    out.append("\n## G1: committee enforced at every check (Block F B and C settings)\n")
    same_runs, total_runs, same_dec, total_dec, diffs = 0, 0, 0, 0, []
    for s in adversarial.g_sweeps()["G1"][1]:
        ref = {kk: v for kk, v in s.items() if kk != "ENFORCE_COMMITTEE"}
        sweep = "B" if "MAX_COLLUDERS" in ref else "C"
        a = open(os.path.join(H, "G1", adversarial.name(s), "processed", "runs.csv")).read()
        b = open(os.path.join(F, sweep, adversarial.name(ref), "processed", "runs.csv")).read()
        same_runs += a == b
        total_runs += 1
    ref_f = {(r["setting"], r["run_id"]): r for sw in ("B", "C") for r in load(os.path.join(F, f"{sw}_forgery_runs.csv"))
             if r["variant"] == "voting_reputation_committee"}
    for r in g1f:
        if r["variant"] != "voting_reputation":
            continue
        key = (r["setting"].replace("_enf1", ""), r["run_id"])
        total_dec += 1
        same = r["accepted"] == ref_f[key]["accepted"]
        same_dec += same
        if not same:
            diffs.append(key)
    out.append(f"- Genuine `runs.csv` byte-identical to Block F: **{same_runs} of {total_runs} settings**.")
    out.append(f"- Default-level forged-alert decision equal to the Block F committee-level decision: **{same_dec} of "
               f"{total_dec} runs**" + (f" (differences: {diffs[:10]})" if diffs else "") + ".")
    pivot("G1 forged alert accepted (% of runs) by level", g1f,
          lambda r: (f"{r['MALICIOUS_RATIO']:g}", attacker(r), r["variant"]), ["share", "attacker", "level"],
          lambda r: r["accepted"] if r["variant"] != "no_voting" else float(r["accepted_share"] > 0),
          where=lambda r: r["MALICIOUS_COOPERATION"] == 0.9 or r["ONOFF_DUTY"] >= 0.8 and r["ONOFF_PERIOD_S"] > 0)

# ---------------------------------------------------------------- G2
g2t, g2f, g2g = (load(os.path.join(H, f"G2_{x}_runs.csv")) for x in ("trust", "forgery", "genuine"))
if g2t:
    out.append("\n## G2: committee size and quorum (committee enforced, MAX_COLLUDERS = committee size)\n")
    key = lambda r: (f"{r['COMMITTEE_SIZE']:g}/{r['QUORUM']:g}", f"{r['MALICIOUS_RATIO']:g}", attacker(r))
    hdr = ["m/q", "share", "attacker"]
    pivot("Genuine alert accepted (% of runs)", g2t, key, hdr, lambda r: r["genuine_accepted"])
    pivot("Proposed honest delivery (%), accepted runs", g2g, key, hdr, lambda r: r["honest_delivery"],
          where=lambda r: r["scheme"] == "proposed" and r["accepted"] == 1)
    pivot("Forged alert accepted (% of runs), default level (committee enforced)", g2f, key, hdr,
          lambda r: r["accepted"], where=lambda r: r["variant"] == "voting_reputation")
    pivot("Forged alert accepted (% of runs), voting only (committee enforced)", g2f, key, hdr,
          lambda r: r["accepted"], where=lambda r: r["variant"] == "voting_only")
    pivot("Attackers on the genuine committee", g2t, key, hdr, lambda r: r["attackers_in_committee"], pct=False)
    pivot("Committee size", g2t, key, hdr, lambda r: r["committee_size"], pct=False)
    pivot("Committee full (% of runs)", g2t, key, hdr, lambda r: r["committee_full"])
    pivot("Committee below quorum (% of runs)", g2t, key, hdr, lambda r: r["committee_below_quorum"])
    pivot("Vote frames per run (proposed)", g2g, key, hdr, lambda r: r["vote_tx"], pct=False,
          where=lambda r: r["scheme"] == "proposed")
    pivot("Quorum delay (ms, proposed, accepted runs)", g2g, key, hdr, lambda r: r["quorum_ms"], pct=False, dec=2,
          where=lambda r: r["scheme"] == "proposed" and r["accepted"] == 1)
    pivot("CH route: relayed RSU reception (%)", g2g, key, hdr, lambda r: r["rsu_relay_received"],
          where=lambda r: r["scheme"] == "ch_route" and r["rsu_relay_received"] == r["rsu_relay_received"])
    if c_choice:
        out.append("\n**G2 selection (pre-registered rules)**\n\n| m/q | admissible | criterion 1 violations | criterion 2 "
                   "violations | regressions explained by withholding | pooled genuine accepted | pooled default-level "
                   "forgery accepted |\n|---|---|---|---|---|---|---|")
        for kk, v in c_choice["candidates"].items():
            out.append(f"| {kk} | {v['admissible']} | {len(v['criterion1_violations'])} | "
                       f"{len(v['criterion2_violations'])} | {len(v['withholding_explained_regressions'])} | "
                       f"{100 * v['pooled_genuine_accepted']:.2f} % | {100 * v['pooled_default_forgery_accepted']:.2f} % |")
        out.append(f"\nChosen by the coded rule: **{c_choice['chosen'][0]}/{c_choice['chosen'][1]}**.")
        major = [v for v in c_choice["candidates"].values() if v["admissible"] and 2 * v["q"] > v["m"]]
        best = max(major, key=lambda v: (v["pooled_genuine_accepted"], -v["pooled_default_forgery_accepted"], -v["m"]))
        out.append(f"\nDeviation: the coded candidate list wrongly included the 7/3 contrast arm (plan section 4.1: "
                   f"contrast only; safeguard 5: no weaker quorum). The same rule over majority-quorum candidates "
                   f"(q > m/2) gives **{best['m']}/{best['q']}**. See `G2_RESULTS_REPORT.md`.")
    if c_fixed:
        out.append("\n**G2 selection, corrected (`G2_selection_corrected.json`, G4.1)**: candidates 5/3, 7/4, 9/5 only; "
                   "7/3 is a contrast. *Adoptable* adds plan section 8 criterion 2 on the CH route.\n\n| m/q | candidate | "
                   "admissible (registered) | CH-route violations | adoptable |\n|---|---|---|---|---|")
        for kk, v in c_fixed["candidates"].items():
            out.append(f"| {kk} | {v['candidate']} | {v['admissible']} | {len(v['ch_route_violations'])} | {v['adoptable']} |")
        fmt = lambda x: f"{x[0]}/{x[1]}" if x else "none"
        out.append(f"\nRegistered selection rule over the candidates: **{fmt(c_fixed['selection_rule_choice'])}**. "
                   f"Chosen (also meets the adoption criteria): **{fmt(c_fixed['chosen'])}**.")

# ---------------------------------------------------------------- G3a / G3b
g3a = load(os.path.join(H, "G3a_trust_runs.csv"))
if g3a:
    out.append("\n## G3a: burst detector calibration (held-out runs 30-59, 10 % attackers)\n")
    key = lambda r: (f"{r['TRUST_BURST_K']:g}", attacker(r))
    pivot("Honest vehicles flagged (%) — false alarm", g3a, key, ["k", "attacker"], lambda r: r["honest_flagged"],
          dec=2)
    pivot("Attackers flagged (%) — detection", g3a, key, ["k", "attacker"], lambda r: r["attackers_flagged"])
    pivot("Attackers ineligible (%) — below gate or flagged", g3a, key, ["k", "attacker"],
          lambda r: r["attackers_ineligible"])
    pivot("Honest vehicles ineligible (%)", g3a, key, ["k", "attacker"], lambda r: r["honest_ineligible"], dec=2)
    out.append("\n```\n" + json.dumps(k_choice, indent=1) + "\n```" if k_choice else "\n(no G3a choice file)")
g3b_t, g3b_f, g3b_g = (load(os.path.join(H, f"G3b_{x}_runs.csv")) for x in ("trust", "forgery", "genuine"))
if g3b_t:
    out.append(f"\n## G3b: burst detector k = {k} on the Block F C and per-second-0.9 settings (runs 0-29)\n")
    key = lambda r: (f"{r['MALICIOUS_RATIO']:g}", attacker(r))
    ref_t = [r for sw in ("B", "C") for r in load(os.path.join(F, f"{sw}_trust_runs.csv"))
             if sw == "C" or (r["MALICIOUS_COOPERATION"] == 0.9 and r["MAX_COLLUDERS"] == 5)]
    ref_f = [r for sw in ("B", "C") for r in load(os.path.join(F, f"{sw}_forgery_runs.csv"))
             if sw == "C" or (r["MALICIOUS_COOPERATION"] == 0.9 and r["MAX_COLLUDERS"] == 5)]
    for title, rows, val in (("Attackers ineligible (%) — G3b", g3b_t, lambda r: r["attackers_ineligible"]),
                             ("Attackers below gate (%) — Block F reference", ref_t, lambda r: r["attackers_below_gate"]),
                             ("Attackers flagged only by the detector (%) (Beta trust >= gate)", g3b_t,
                              lambda r: r["attackers_flag_only"]),
                             ("Honest vehicles flagged (%) — false alarm", g3b_t, lambda r: r["honest_flagged"]),
                             ("Genuine alert accepted (%) — G3b", g3b_t, lambda r: r["genuine_accepted"]),
                             ("Genuine alert accepted (%) — Block F reference", ref_t, lambda r: r["genuine_accepted"]),
                             ("Attackers on the genuine committee — G3b", g3b_t, lambda r: r["attackers_in_committee"]),
                             ("Attackers on the genuine committee — Block F", ref_t,
                              lambda r: r["attackers_in_committee"])):
        pivot(title, rows, key, ["share", "attacker"], val, pct="committee" not in title)
    for level in ("voting_reputation", "voting_reputation_committee"):
        pivot(f"Forged alert accepted (%) — {level} — G3b", g3b_f, key, ["share", "attacker"], lambda r: r["accepted"],
              where=lambda r, v=level: r["variant"] == v)
        pivot(f"Forged alert accepted (%) — {level} — Block F", ref_f, key, ["share", "attacker"],
              lambda r: r["accepted"], where=lambda r, v=level: r["variant"] == v)
    pivot("Proposed honest delivery (%), accepted runs — G3b", g3b_g, key, ["share", "attacker"],
          lambda r: r["honest_delivery"], where=lambda r: r["scheme"] == "proposed" and r["accepted"] == 1)

# ---------------------------------------------------------------- G4
g4t, g4f, g4g = (load(os.path.join(H, f"G4_{x}_runs.csv")) for x in ("trust", "forgery", "genuine"))
if g4t:
    out.append(f"\n## G4: combined configuration (committee {committee}, enforced, k = {k})\n")
    key = lambda r: (f"{r['MALICIOUS_RATIO']:g}", attacker(r))
    for title, rows, val, w in (
            ("Genuine alert accepted (%)", g4t, lambda r: r["genuine_accepted"], lambda r: True),
            ("Forged alert accepted (%), default level", g4f, lambda r: r["accepted"],
             lambda r: r["variant"] == "voting_reputation"),
            ("Honest vehicles ineligible (%)", g4t, lambda r: r["honest_ineligible"], lambda r: True),
            ("Attackers ineligible (%)", g4t, lambda r: r["attackers_ineligible"], lambda r: True),
            ("Proposed honest delivery (%), accepted runs", g4g, lambda r: r["honest_delivery"],
             lambda r: r["scheme"] == "proposed" and r["accepted"] == 1)):
        pivot(title, rows, key, ["share", "attacker"], val, where=w)

open(os.path.join(H, "BLOCK_G_TABLES.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print(f"wrote {os.path.join(H, 'BLOCK_G_TABLES.md')} ({len(out)} lines)")
