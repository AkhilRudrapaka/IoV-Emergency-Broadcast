"""Block F: regenerate results/adversarial/BLOCK_F_TABLES.md from the sweep CSVs (read-only analysis, no simulation).

    python -X utf8 results/adversarial/analysis/blockf_tables.py      (run from the project root)

Every cell: mean ± 95% CI half-width over independent runs (metrics.summarize: Student t, df = n - 1; NaN runs
excluded), with n. Percentages are shares of runs (acceptance, detection) or of vehicles (delivery, false alarm)."""
import csv
import glob
import json
import os
import sys

sys.path.insert(0, os.getcwd())
import adversarial
from metrics import summarize

R = os.path.join("results", "adversarial")
D = ("100", "200", "300")
ALIAS = {"MALICIOUS_RATIO": "ratio", "MALICIOUS_DROP_PROB": "pdrop", "MALICIOUS_COOPERATION": "coop",
         "MAX_COLLUDERS": "colluders", "ONOFF_PERIOD_S": "period", "ONOFF_DUTY": "duty", "TRUST_CH_THRESHOLD": "gate"}
KEYS = {"A": ["MALICIOUS_RATIO", "MALICIOUS_DROP_PROB", "MALICIOUS_COOPERATION"],
        "B": ["MALICIOUS_RATIO", "MALICIOUS_COOPERATION", "MAX_COLLUDERS"],
        "C_calibration": ["MALICIOUS_COOPERATION", "ONOFF_DUTY", "ONOFF_PERIOD_S", "TRUST_CH_THRESHOLD"],
        "C": ["MALICIOUS_RATIO", "ONOFF_DUTY", "ONOFF_PERIOD_S"],
        "C_gate": ["MALICIOUS_COOPERATION", "ONOFF_DUTY", "ONOFF_PERIOD_S", "TRUST_CH_THRESHOLD"]}
out = []


def load(name):
    p = os.path.join(R, name)
    rows = list(csv.DictReader(open(p, encoding="utf-8"))) if os.path.exists(p) else []
    for r in rows:
        for k, v in r.items():
            try:
                r[k] = float(v)
            except ValueError:
                pass
    return rows


def cell(vals, pct=True, dec=1):
    m, _, ci, n = summarize([v for v in vals if v is not None])
    if n == 0:
        return "–"
    s = 100 if pct else 1
    return f"{m * s:.{dec}f} ± {ci * s:.{dec}f} (n={n})" if ci == ci else f"{m * s:.{dec}f} (n={n})"


def pivot(title, rows, keys, value, pct=True, where=lambda r: True, dec=1):
    rows = [r for r in rows if where(r)]
    out.append(f"\n**{title}**\n")
    out.append("| " + " | ".join(ALIAS[k] for k in keys) + " | " + " | ".join(f"{d} vehicles" for d in D) + " |")
    out.append("|" + "---|" * (len(keys) + len(D)))
    for s in sorted({tuple(r[k] for k in keys) for r in rows}):
        sel = [r for r in rows if tuple(r[k] for k in keys) == s]
        out.append("| " + " | ".join(f"{v:g}" for v in s) + " | " + " | ".join(
            cell([value(r) for r in sel if r["density"] == float(d)], pct, dec) for d in D) + " |")


out.append("# Block F: adversarial sweep tables\n")
out.append("Generated by `results/adversarial/analysis/blockf_tables.py` from `results/adversarial/*_runs.csv`. "
           "Cell = mean ± 95% CI half-width over independent runs (Student t), n = runs. Seeds: runs 0-29 "
           "(C_calibration: held-out runs 30-59); seed = 10000 + 100·density + run. Gate 0.70 unless a gate column says "
           "otherwise. The VeReMi ML model is not used.\n")
out.append("## Sweep completion\n")
out.append("| sweep | settings | completed | raw records | runs.csv rows | forgery rows | seeds |\n|---|---|---|---|---|---|---|")
gate = json.load(open(os.path.join(R, "C_calibration_choice.json")))["chosen_gate"]
for sweep, (first, settings) in adversarial.sweeps(gate).items():
    done = raws = runs = frg = 0
    for s in settings:
        f = os.path.join(R, sweep, adversarial.name(s))
        if os.path.exists(os.path.join(f, "summaries", "experiment_config.json")):
            done += 1
            raws += len([p for p in glob.glob(os.path.join(f, "raw", "d*_r*.json.gz")) if "__" not in p])
            runs += sum(1 for _ in open(os.path.join(f, "processed", "runs.csv"))) - 1
            frg += sum(1 for _ in open(os.path.join(f, "processed", "forgery_runs.csv"))) - 1
    out.append(f"| {sweep} | {len(settings)} | {done} | {raws} | {runs} | {frg} | runs {first}-{first + 29} |")

for sweep, keys in KEYS.items():
    gen, tru, frg = load(f"{sweep}_genuine_runs.csv"), load(f"{sweep}_trust_runs.csv"), load(f"{sweep}_forgery_runs.csv")
    out.append(f"\n## {sweep}")
    pivot("Genuine alert accepted (% of runs)", tru, keys, lambda r: r["genuine_accepted"])
    pivot("Proposed: honest delivery (% of reachable honest vehicles), runs whose genuine alert was accepted", gen, keys,
          lambda r: r["honest_delivery"], where=lambda r: r["scheme"] == "proposed" and r["accepted"] == 1)
    pivot("Flooding: honest delivery (%), accepted runs", gen, keys, lambda r: r["honest_delivery"],
          where=lambda r: r["scheme"] == "flooding" and r["accepted"] == 1)
    pivot("CH route: relayed RSU reception (% of incidents outside direct RSU range)", gen, keys,
          lambda r: r["rsu_relay_received"], where=lambda r: r["scheme"] == "ch_route" and r["rsu_relay_received"] == r["rsu_relay_received"])
    pivot("Proposed: alert copies dropped per run", gen, keys, lambda r: r["dropped"], pct=False,
          where=lambda r: r["scheme"] == "proposed")
    pivot("Trust AUC (probability an attacker's trust is below an honest vehicle's)", tru, keys,
          lambda r: r["trust_auc"], pct=False, dec=3)
    pivot("Detection: attackers below the gate (%)", tru, keys, lambda r: r["attackers_below_gate"])
    pivot("False alarm: honest vehicles below the gate (%)", tru, keys, lambda r: r["honest_below_gate"])
    pivot("Attackers on the genuine alert's committee (of 5)", tru, keys, lambda r: r["attackers_in_committee"], pct=False)
    pivot("Genuine certificate would pass the committee check (% of accepted genuine alerts)", tru, keys,
          lambda r: r["genuine_passes_committee_check"], where=lambda r: r["genuine_accepted"] == 1)
    for variant, label in (("voting_reputation", "default full level"), ("voting_reputation_committee", "opt-in committee level"),
                           ("voting_only", "voting, no reputation gate"), ("no_voting", "no voting")):
        if any(r["variant"] == variant for r in frg):
            pivot(f"Forged alert accepted (% of runs) — {label}", frg, keys,
                  (lambda r: float(r["accepted_share"] > 0)) if variant == "no_voting" else (lambda r: r["accepted"]),
                  where=lambda r, v=variant: r["variant"] == v)
    pivot("Forged certificate formed (% of runs: at least 3 colluding neighbours voted)", frg, keys,
          lambda r: r["certificate_formed"], where=lambda r: r["variant"] == "voting_reputation")
    pivot("Accepted forgeries at the default level: reputable endorsers who were committee members (of 3)", frg, keys,
          lambda r: r["reputable_endorsers_in_committee"], pct=False,
          where=lambda r: r["variant"] == "voting_reputation" and r["accepted"] == 1)

out.append("\n## C_calibration choice\n\n```\n" + open(os.path.join(R, "C_calibration_choice.json")).read() + "\n```")
open(os.path.join(R, "BLOCK_F_TABLES.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print(f"wrote {os.path.join(R, 'BLOCK_F_TABLES.md')} ({len(out)} lines)")
